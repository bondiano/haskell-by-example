module Data.Chess
  ( KnightPos
  , moveKnight
  ) where

-- | Позиция на шахматной доске (столбец, строка), от (1,1) до (8,8).
type KnightPos = (Int, Int)

-- | Все допустимые ходы коня с данной позиции.
-- Конь ходит буквой «Г»: 2 клетки в одном направлении, 1 в перпендикулярном.
-- Возвращает только позиции в пределах доски 8×8.
--
-- >>> moveKnight (4, 4)
-- [(6,5),(6,3),(2,5),(2,3),(5,6),(5,2),(3,6),(3,2)]
--
-- >>> moveKnight (1, 1)
-- [(3,2),(2,3)]
moveKnight :: KnightPos -> [KnightPos]
moveKnight (c, r) = filter onBoard
  [ (c+2, r+1), (c+2, r-1)
  , (c-2, r+1), (c-2, r-1)
  , (c+1, r+2), (c+1, r-2)
  , (c-1, r+2), (c-1, r-2)
  ]
  where
    onBoard (c', r') = c' >= 1 && c' <= 8 && r' >= 1 && r' <= 8
